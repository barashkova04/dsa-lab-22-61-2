#!/bin/bash

# Проверка количества аргументов
if [ $# -ne 1 ]; then
    echo "Ошибка: Необходимо указать один аргумент - имя файла"
    exit 1
fi

file="$1"

# Проверка существования файла
if [ ! -f "$file" ]; then
    echo "Ошибка: Файл '$file' не существует"
    exit 1
fi

# Проверка, что файл текстовый (ИНВЕРТИРОВАННОЕ условие)
if ! file "$file" | grep -q text; then
    echo "Ошибка: Файл '$file' не является текстовым файлом"
    exit 1
fi

# Проверка что файл не пустой
if [ ! -s "$file" ]; then
    echo "Ошибка: Файл '$file' пуст"
    exit 1
fi

# Вывод статистики
echo "Статистика для файла: $file"
echo "Количество строк: $(wc -l < "$file")"
echo "Количество слов: $(wc -w < "$file")"
echo "Количество символов: $(wc -m < "$file")"

